using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MigrationModelCompiler;

public sealed record ModelProjection(string Forwarder, string? Helper)
{
	public static ModelProjection Create(string source, string batch, string fileName)
	{
		var root = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Latest))
			.GetCompilationUnitRoot();
		if (root.GetDiagnostics().Any(x => x.Severity == DiagnosticSeverity.Error))
		{
			throw new InvalidDataException($"Invalid C# in migration designer {fileName}.");
		}

		var spaces = root.Members.OfType<BaseNamespaceDeclarationSyntax>().ToArray();
		if (root.Members.Count != 1 || spaces.Length != 1 || spaces[0].Name.ToString() != "MudSharp.Migrations" ||
		    spaces[0].Members.Count != 1 || spaces[0].Members[0] is not ClassDeclarationSyntax type ||
		    !type.Modifiers.Any(SyntaxKind.PartialKeyword) || type.BaseList is not null || type.TypeParameterList is not null)
		{
			throw new InvalidDataException($"Unsupported migration designer declaration: {fileName}.");
		}

		var attributes = type.AttributeLists.SelectMany(x => x.Attributes).ToArray();
		if (attributes.Length != 2 || attributes.Count(x => x.Name.ToString() == "DbContext") != 1 ||
		    attributes.Count(x => x.Name.ToString() == "Migration") != 1)
		{
			throw new InvalidDataException($"Expected one DbContext and Migration attribute: {fileName}.");
		}

		if (type.Members.Count == 0) return new ModelProjection(source, null);
		if (type.Members.Count != 1 || type.Members[0] is not MethodDeclarationSyntax method ||
		    method.Identifier.ValueText != "BuildTargetModel" || method.ReturnType.ToString() != "void" ||
		    !method.Modifiers.Any(SyntaxKind.OverrideKeyword) || method.ParameterList.Parameters.Count != 1 ||
		    method.ParameterList.Parameters[0].Type?.ToString() != "ModelBuilder" || method.Body is null ||
		    method.Body.DescendantNodes().Any(x => x is ThisExpressionSyntax or BaseExpressionSyntax))
		{
			throw new InvalidDataException($"Unsupported BuildTargetModel shape: {fileName}.");
		}

		var helperName = "Model_" + type.Identifier.ValueText;
		var helperNamespace = "MudSharp.MigrationModels." + batch;
		var parameter = method.ParameterList.Parameters[0].Identifier.Text;
		var forwardingBody = SyntaxFactory.ParseStatement(
			$"{{ global::{helperNamespace}.{helperName}.Build({parameter}); }}") as BlockSyntax;
		var forwarder = root.ReplaceNode(method.Body, forwardingBody!).ToFullString();
		var usings = root.Usings.Where(x => x.Name?.ToString() is not ("MudSharp" or "MudSharp.Database"));
		// Keep the original model-building block verbatim, including directives and literal values.
		var helper = "// <auto-generated />\n#nullable disable\n" +
		             string.Join("\n", usings.Select(x => x.ToString())) +
		             $"\nnamespace {helperNamespace};\npublic static class {helperName}\n{{\n" +
		             $"public static void Build{method.ParameterList}\n{method.Body.ToFullString()}\n}}\n";
		return new ModelProjection(forwarder, helper);
	}
}
