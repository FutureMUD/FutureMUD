				new XElement("UnloadEmote", new XCData("@ open|opens $1 and remove|removes $2.")),
				new XElement("UnreadyEmote", new XCData("@ open|opens $1 and clear|clears $2 from its breech.")),
				new XElement("UnreadyEmoteNoChamberedRound",
					new XCData("@ check|checks the empty breech of $1.")),
				new XElement("FireEmote",
					new XCData("@ squeeze|squeezes the trigger on $2 and launch|launches a grenade toward $1.")),
				new XElement("FireEmoteNoChamberedRound",
					new XCData("@ squeeze|squeezes the trigger on $2, producing only a hollow click.")),
