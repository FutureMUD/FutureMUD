	private int EnsureModernFirearmSamples(FuturemudDatabaseContext context)
	{
		var changes = 0;
		var account = context.Accounts.First();
		var now = DateTime.UtcNow;

		EditableItem CreateEditableItem()
		{
			return new EditableItem
			{
				RevisionNumber = 0,
				RevisionStatus = 4,
				BuilderAccountId = account.Id,
				BuilderDate = now,
				BuilderComment = "Auto-generated by the system",
				ReviewerAccountId = account.Id,
				ReviewerComment = "Auto-generated by the system",
				ReviewerDate = now
			};
		}

		TraitDefinition EnsureLongarmsSkill()
		{
			var existing = context.TraitDefinitions.FirstOrDefault(x => x.Name == "Longarms");
			if (existing is not null)
			{
				return existing;
			}

			var dexterity = context.TraitDefinitions
				.Where(x => x.Type == 1 || x.Type == 3)
				.FirstOrDefault(x => x.Name == "Agility" || x.Name == "Dexterity" || x.Name == "Speed") ??
			                context.TraitDefinitions.First(x => x.Type == 1 || x.Type == 3);
			var expression = new TraitExpression
			{
				Name = "Longarms Skill Cap",
				Expression = $"min(99,5.5*{dexterity.Alias}:{dexterity.Id})"
			};
			var skill = new TraitDefinition
			{
				Name = "Longarms",
				Type = (int)TraitType.Skill,
				Expression = expression,
				TraitGroup = "Combat",
				AvailabilityProg = context.FutureProgs.First(x => x.FunctionName == "AlwaysTrue"),
				TeachableProg = context.FutureProgs.First(x => x.FunctionName == "AlwaysFalse"),
				LearnableProg = context.FutureProgs.First(x => x.FunctionName == "AlwaysTrue"),
				TeachDifficulty = 7,
				LearnDifficulty = 7,
				Hidden = false,
				ImproverId = context.Improvers.First(x => x.Name == "Skill Improver").Id,
				DecoratorId = context.TraitDecorators.First(x => x.Name == "General Skill").Id,
				DerivedType = 0,
				ChargenBlurb = string.Empty,
				BranchMultiplier = 1.0
			};
			context.TraitDefinitions.Add(skill);
			context.SaveChanges();
			changes++;
			return skill;
		}

		RangedWeaponTypes EnsureRangedType(string name, string grade, AmmunitionLoadType loadType,
			int ammunitionCapacity, bool fireableInMelee, int range, double stamina, double fireDelay,
			double aimLoss)
		{
			var existing = context.RangedWeaponTypes.FirstOrDefault(x => x.Name == name);
			if (existing is not null)
			{
				var repaired = false;
				if (existing.AmmunitionLoadType != (int)loadType)
				{
					existing.AmmunitionLoadType = (int)loadType;
					repaired = true;
				}

				if (existing.AmmunitionCapacity != ammunitionCapacity)
				{
					existing.AmmunitionCapacity = ammunitionCapacity;
					repaired = true;
				}

				if (repaired)
				{
					changes++;
				}

				return existing;
			}

			var skill = EnsureLongarmsSkill();
			var ranged = new RangedWeaponTypes
			{
				Name = name,
				Classification = (int)WeaponClassification.Lethal,
				FireTrait = skill,
				OperateTrait = skill,
				FireableInMelee = fireableInMelee,
				DefaultRangeInRooms = range,
				AccuracyBonusExpression = "(-1.5*range)-(pow(1-aim,2)*4.0)",
				DamageBonusExpression = "-6*range",
				AmmunitionLoadType = (int)loadType,
				SpecificAmmunitionGrade = grade,
				AmmunitionCapacity = ammunitionCapacity,
				RangedWeaponType = (int)RangedWeaponType.ModernFirearm,
				StaminaToFire = stamina,
				StaminaPerLoadStage = 7.0,
				CoverBonus = -3.0,
				BaseAimDifficulty = (int)Difficulty.Normal,
				LoadDelay = 1.2,
				ReadyDelay = 0.4,
				FireDelay = fireDelay,
				AimBonusLostPerShot = aimLoss,
				RequiresFreeHandToReady = true,
				AlwaysRequiresTwoHandsToWield = true
			};
			context.RangedWeaponTypes.Add(ranged);
			context.SaveChanges();
			changes++;
			return ranged;
		}

		AmmunitionTypes EnsureAmmunition(string name, string grade, int projectiles, RangedScatterType? scatterType,
			double spreadPenalty, string damage)
		{
			var existing = context.AmmunitionTypes.FirstOrDefault(x => x.Name == name);
			if (existing is not null)
			{
				var repaired = false;
				if (existing.ProjectileCount != projectiles)
				{
					existing.ProjectileCount = projectiles;
					repaired = true;
				}

				int? scatterValue = scatterType is null ? null : (int)scatterType.Value;
				if (existing.ScatterType != scatterValue)
				{
					existing.ScatterType = scatterValue;
					repaired = true;
				}

				if (Math.Abs(existing.SpreadPenalty - spreadPenalty) > 0.0001)
				{
					existing.SpreadPenalty = spreadPenalty;
					repaired = true;
				}

				if (repaired)
				{
					changes++;
				}

				return existing;
			}

			var ammunition = new AmmunitionTypes
			{
				Name = name,
				SpecificType = grade,
				RangedWeaponTypes = ((int)RangedWeaponType.ModernFirearm).ToString(),
				BaseAccuracy = 0.0,
				Loudness = (int)AudioVolume.ExtremelyLoud,
				BreakChanceOnHit = 0.2,
				BreakChanceOnMiss = 0.5,
				BaseBlockDifficulty = (int)Difficulty.Insane,
				BaseDodgeDifficulty = (int)Difficulty.Insane,
				DamageExpression = damage,
				StunExpression = damage,
				PainExpression = damage,
				DamageType = (int)DamageType.Ballistic,
				ProjectileCount = projectiles,
				ScatterType = scatterType is null ? null : (int)scatterType.Value,
				SpreadPenalty = spreadPenalty
			};
			context.AmmunitionTypes.Add(ammunition);
			context.SaveChanges();
			changes++;
			return ammunition;
		}

		GameItemComponentProto EnsureComponent(string type, string name, string description, XElement definition)
		{
			var existing = context.GameItemComponentProtos
				.FirstOrDefault(x => x.Type == type && x.Name == name);
			if (existing is not null)
			{
				return existing;
			}

			var component = new GameItemComponentProto
			{
				Id = context.GameItemComponentProtos.Any()
					? context.GameItemComponentProtos.Max(x => x.Id) + 1
					: 1,
				RevisionNumber = 0,
				EditableItem = CreateEditableItem(),
				Type = type,
				Name = name,
				Description = description,
				Definition = definition.ToString()
			};
			context.GameItemComponentProtos.Add(component);
			context.SaveChanges();
			changes++;
			return component;
		}

		GameItemProto EnsureItemPrototype(string uniqueName, string name, string keywords, string shortDescription,
			string longDescription, string fullDescription, SizeCategory size, double weight,
			params GameItemComponentProto[] components)
		{
			var item = context.GameItemProtos.FirstOrDefault(x => x.UniqueName == uniqueName);
			if (item is null)
			{
				var material = context.Materials.FirstOrDefault(x => x.Name == "Steel") ??
				               context.Materials.First();
				item = new GameItemProto
				{
					Id = context.GameItemProtos.Any() ? context.GameItemProtos.Max(x => x.Id) + 1 : 1,
					Name = name,
					UniqueName = uniqueName,
					RevisionNumber = 0,
					EditableItem = CreateEditableItem(),
					Keywords = keywords,
					ShortDescription = shortDescription,
					LongDescription = longDescription,
					FullDescription = fullDescription,
					Size = (int)size,
					Weight = weight,
					MaterialId = material.Id,
					ReadOnly = false,
					BaseItemQuality = (int)ItemQuality.Standard,
					PermitPlayerSkins = true
				};
				context.GameItemProtos.Add(item);
				context.SaveChanges();
				changes++;
			}

			foreach (var component in components.DistinctBy(x => (x.Id, x.RevisionNumber)))
			{
				if (context.GameItemProtosGameItemComponentProtos.Any(x =>
					    x.GameItemProtoId == item.Id &&
					    x.GameItemProtoRevision == item.RevisionNumber &&
					    x.GameItemComponentProtoId == component.Id &&
					    x.GameItemComponentRevision == component.RevisionNumber))
				{
					continue;
				}

				context.GameItemProtosGameItemComponentProtos.Add(new GameItemProtosGameItemComponentProtos
				{
					GameItemProtoId = item.Id,
					GameItemProtoRevision = item.RevisionNumber,
					GameItemComponentProtoId = component.Id,
					GameItemComponentRevision = component.RevisionNumber
				});
				changes++;
			}

			context.SaveChanges();
			return item;
		}

		XElement FirearmDefinition(RangedWeaponTypes type, bool internalMagazine)
		{
			return new XElement("Definition",
				new XElement("LoadEmote", new XCData("@ insert|inserts $2 into $1.")),
				new XElement("ReadyEmote", new XCData("@ work|works the action on $1.")),
				new XElement("UnloadEmote", new XCData("@ unload|unloads $2 from $1.")),
				new XElement("UnreadyEmote", new XCData("@ clear|clears $2 from $1's chamber.")),
				new XElement("UnreadyEmoteNoChamberedRound",
					new XCData("@ check|checks $1's already empty chamber.")),
				new XElement("FireEmote", new XCData("@ squeeze|squeezes the trigger on $2 and $2 fires.")),
				new XElement("FireEmoteNoChamberedRound",
					new XCData("@ squeeze|squeezes the trigger on $2, producing only a click.")),
				new XElement("RangedWeaponType", type.Id),
				internalMagazine ? new XElement("InternalMagazineCapacity", 6) : null,
				internalMagazine ? new XElement("EjectOnFire", true) : new XElement("ClipType", "STANAG 5.56"),
				new XElement("CycleType", internalMagazine ? FirearmCycleType.Manual : FirearmCycleType.SelfLoading),
				new XElement("AttachmentSlots",
					new XElement("Slot", new XAttribute("name", "optic"), new XAttribute("type", "Optic"),
						new XAttribute("formFactor", "picatinny")),
					new XElement("Slot", new XAttribute("name", "muzzle"), new XAttribute("type", "Muzzle"),
						new XAttribute("formFactor", internalMagazine ? "12ga-threaded" : "5.56-threaded")),
					new XElement("Slot", new XAttribute("name", "stock"), new XAttribute("type", "Stock"),
						new XAttribute("formFactor", "buffer-tube")),
					new XElement("Slot", new XAttribute("name", "grip"), new XAttribute("type", "Grip"),
						new XAttribute("formFactor", "picatinny")),
					new XElement("Slot", new XAttribute("name", "underbarrel"),
						new XAttribute("type", "Underbarrel"), new XAttribute("formFactor", "picatinny")),
					new XElement("Slot", new XAttribute("name", "side"), new XAttribute("type", "Side"),
						new XAttribute("formFactor", "picatinny")),
					new XElement("Slot", new XAttribute("name", "bayonet"), new XAttribute("type", "Bayonet"),
						new XAttribute("formFactor", "modern-lug"))),
				new XElement("FireModes",
					new XElement("Mode", new XAttribute("type", "Single"), new XAttribute("rounds", 1),
						new XAttribute("recoil", 0.0), new XAttribute("stamina", 0.0),
						new XAttribute("delay", 0.0)),
					internalMagazine
						? null
						: new XElement("Mode", new XAttribute("type", "Burst"), new XAttribute("rounds", 3),
							new XAttribute("recoil", 1.0), new XAttribute("stamina", 2.0),
							new XAttribute("delay", 0.08)),
					internalMagazine
						? null
						: new XElement("Mode", new XAttribute("type", "Automatic"), new XAttribute("rounds", 6),
							new XAttribute("recoil", 1.25), new XAttribute("stamina", 2.5),
							new XAttribute("delay", 0.1))));
		}

