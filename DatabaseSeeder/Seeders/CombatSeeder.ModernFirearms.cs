		GameItemComponentProto EnsureAttachment(string name, FirearmAttachmentSlotType slotType, string[] formFactors,
			double accuracy = 0.0, double aim = 0.0, double damage = 1.0, double range = 1.0,
			double recoil = 1.0, double stamina = 1.0, double delay = 1.0, double aimLoss = 1.0,
			int loudness = 0, string? fireEmote = null, IReadOnlyCollection<Type>? requiredCapabilities = null)
		{
			return EnsureComponent("FirearmAttachment", name.Replace(' ', '_'),
				$"Turns an item into a {name.ToLowerInvariant()} firearm attachment",
				new XElement("Definition",
					new XElement("SlotType", slotType),
					new XElement("FormFactors", formFactors.Select(x => new XElement("FormFactor", x))),
					new XElement("Modifiers",
						new XAttribute("accuracy", accuracy),
						new XAttribute("aim", aim),
						new XAttribute("damage", damage),
						new XAttribute("range", range),
						new XAttribute("recoil", recoil),
						new XAttribute("stamina", stamina),
						new XAttribute("delay", delay),
						new XAttribute("aimloss", aimLoss),
						new XAttribute("loudness", loudness)),
					new XElement("FireEmote", new XCData(fireEmote ?? string.Empty)),
					new XElement("Requirements",
						(requiredCapabilities ?? [])
						.Select(x => new XElement("Requirement",
							new XAttribute("capability", x.FullName ?? x.Name))))));
		}

