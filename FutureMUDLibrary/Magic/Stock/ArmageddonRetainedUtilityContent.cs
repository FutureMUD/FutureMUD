#nullable enable
using System;
using System.Collections.Generic;
using System.Xml.Linq;
using MudSharp.FutureProg;

namespace MudSharp.Magic;

/// <summary>Live catalogue dependencies; text/link progs must compile with their native typed signatures.</summary>
public sealed record ArmageddonRetainedUtilityBindings(long IdentifyTextProgId,
	long ReciteLinkProgId, long DeadSpeakLinkProgId, string? CharacterEligibilitySource = null,
	string? CorpseEligibilitySource = null)
{
	public void Validate()
	{
		ArmageddonPrimitiveSpellBindings.RequirePositive(IdentifyTextProgId, nameof(IdentifyTextProgId));
		ArmageddonPrimitiveSpellBindings.RequirePositive(ReciteLinkProgId, nameof(ReciteLinkProgId));
		ArmageddonPrimitiveSpellBindings.RequirePositive(DeadSpeakLinkProgId, nameof(DeadSpeakLinkProgId));
		if (CharacterEligibilitySource is not null && string.IsNullOrWhiteSpace(CharacterEligibilitySource)) throw new ArgumentException("Character eligibility source must not be empty.");
		if (CorpseEligibilitySource is not null && string.IsNullOrWhiteSpace(CorpseEligibilitySource)) throw new ArgumentException("Corpse eligibility source must not be empty.");
	}
}

/// <summary>Four native retained mechanisms; world and dependency policy qualification remain separate.</summary>
public static class ArmageddonRetainedUtilityContent
{
	public static IReadOnlyList<ArmageddonCanonicalSpellContribution> Create(ArmageddonRetainedUtilityBindings bindings)
	{
		ArgumentNullException.ThrowIfNull(bindings); bindings.Validate();
		return Array.AsReadOnly(new[]
		{
			Build("lightning", "luminous_trail", "Luminous Trail", 7, 60, "60*grade", "character",
				"Increase future native visual track intensity by 1+0.25*selected grade. Normal tracking permissions and olfactory intensity remain unchanged.",
				Effect("trackmark", new XElement("VisualMultiplier", 1.0), new XElement("OlfactoryMultiplier", 1.0),
					new XElement("VisualBonus", 0.0), new XElement("OlfactoryBonus", 0.0), new XElement("MarkTracks", true),
					new XElement("SDescAddendum", new XCData("(leaving luminous tracks)")), new XElement("AddendumColour", "Bold Cyan")),
				bindings.CharacterEligibilitySource, new XElement("Binding", new XAttribute("list", "target"), new XAttribute("index", 0),
					new XAttribute("effect", "trackmark"), new XAttribute("field", "VisualTrackIntensityMultiplier"), new XCData("1+0.25*grade"))),
			Build("void", "read_enchantment", "Read Enchantment", 7, 40, "60*grade", "character",
				"Give one recipient authored, explicitly permitted character LOOK information through the supplied text prog. No debugging information is generated by this effect.",
				Effect("identify", new XElement("IdentifyProgId", bindings.IdentifyTextProgId)), bindings.CharacterEligibilitySource),
			Build("void", "echo_servant", "Echo Servant", 7, 30, "60*grade", "character",
				"Relay authorised heard speech from the supplied link prog's speaker through one selected proxy using native language output. No command dispatch or recursive casting is performed.",
				Effect("reciteproxy", new XElement("LinkProgId", bindings.ReciteLinkProgId), new XElement("RelayChance", 1.0),
					new XElement("TargetEcho", new XCData("")), new XElement("ReciteEcho", new XCData("@ recite|recites in a hollow borrowed voice"))), bindings.CharacterEligibilitySource),
			Build("void", "voice_of_remains", "Voice of Remains", 33, 40, "60*grade", "item",
				"Raise a temporary corpse-bound speech proxy for the supplied authorised speaker. Native original-body and same-corpse restoration rules apply; no resurrection or account control is granted.",
				Effect("deadspeak", new XElement("LinkProgId", bindings.DeadSpeakLinkProgId), new XElement("AllowPCs", true),
					new XElement("AllowNPCs", true), new XElement("AllowAdmins", false), new XElement("AllowFinal", true),
					new XElement("AllowSkeletal", false), new XElement("RelayChance", 1.0), new XElement("TargetEcho", new XCData("")),
					new XElement("RoomEcho", new XCData("@ jerk|jerks upright, dead lips moving with borrowed words.")),
					new XElement("CollapseEcho", new XCData("@ collapse|collapses as the borrowed voice leaves &0.")),
					new XElement("RestoreEcho", new XCData("@ settle|settles back into $1.")),
					new XElement("ReciteEcho", new XCData("@ recite|recites in a hollow borrowed voice"))), bindings.CorpseEligibilitySource)
		});
	}

	/// <summary>Candidate only: native recursion fencing exists, but a one-attack lifetime consumption/commit adapter is still required. Excluded from Create.</summary>
	public static ArmageddonCanonicalSpellContribution CreateReflectionCandidate(long fireSchoolId, string? eligibilitySource = null)
	{
		ArmageddonPrimitiveSpellBindings.RequirePositive(fireSchoolId, nameof(fireSchoolId));
		return Build("void", "turn_the_elements", "Turn the Elements", 7, 40, "30*grade", "character",
			"Unqualified reflection candidate: native incoming Fire-school reflection has recursion fencing but lacks the locked one-attack lifetime consumption. Do not install as completed stock.",
			Effect("personalward", new XElement("School", fireSchoolId), new XElement("Mode", "Reflect"),
				new XElement("Coverage", "Incoming"), new XElement("IncludesSubschools", false), new XElement("Prog", 0L)), eligibilitySource);
	}

	private static XElement Effect(string token, params object[] fields) => new("Effect", new XAttribute("type", token), fields);
	private static ArmageddonCanonicalSpellContribution Build(string school, string suffix, string name, double floor,
		int opening, string duration, string trigger, string description, XElement effect, string? eligibility, XElement? binding = null)
	{
		var key = "arm.spell." + suffix;
		return new("arm.capability." + school, new ArmageddonUtilitySpellContent(key, name, description, duration, floor,
			"$0 shape|shapes an enchantment around $1.", (resource, cost, filter) =>
			{
				ArmageddonPrimitiveSpellBindings.RequirePositive(resource, nameof(resource));
				ArmageddonPrimitiveSpellBindings.RequirePositive(cost, nameof(cost));
				if (filter < 0) throw new ArgumentOutOfRangeException(nameof(filter));
				if (eligibility is not null) ArmageddonPrimitiveSpellBindings.RequirePositive(filter, nameof(filter));
				var definition = ArmageddonUtilitySpellContent.Definition(key, trigger, resource, cost, filter, opening, floor, new XElement(effect));
				if (binding is not null) definition.Element("ControlledPower")!.Element("ScalarBindings")!.Add(new XElement(binding));
				return definition;
			}, eligibility, trigger == "item" ? ProgVariableTypes.Item : ProgVariableTypes.Character));
	}
}
