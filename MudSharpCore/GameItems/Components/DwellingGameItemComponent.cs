using MudSharp.Construction;
using MudSharp.Construction.Boundary;
using MudSharp.Events;
using MudSharp.Framework.Revision;
using MudSharp.GameItems.Prototypes;
using MudSharp.Effects.Concrete;

namespace MudSharp.GameItems.Components;

public class DwellingGameItemComponent : GameItemComponent
{
    protected DwellingGameItemComponentProto _prototype;
    public override IGameItemComponentProto Prototype => _prototype;

    private long _entranceRoomId;
    private IRoom _entranceRoom;
	private readonly List<long> _instanceRoomIds = new();
	private IExit _accessExit;
	private long _lastExteriorRoomId;
	private IRoom ExteriorRoom => Parent.InInventoryOf == null && Parent.ContainedIn == null
		? ComponentItemTransfer.DirectLocationOf(Parent) : null;
	private void ParentRemovedFromLocation(IPerceivable item)
	{
		if (!_prototype.UsesAuthoredRooms || _accessExit == null) return;
		Gameworld.ExitManager.UnregisterTransientExit(_accessExit);
		_accessExit = null;
	}

    public IRoom EntranceRoom
    {
        get
        {
            if (_entranceRoomId != 0)
            {
                _entranceRoom = Gameworld.Rooms.Get(_entranceRoomId);
                _entranceRoomId = 0;
            }

            return _entranceRoom;
        }
        set => _entranceRoom = value;
    }

    protected override void UpdateComponentNewPrototype(IGameItemComponentProto newProto)
    {
        _prototype = (DwellingGameItemComponentProto)newProto;
    }

    private IRoom GenerateRooms()
    {
		if (_prototype.SharedInterior) return _prototype.TemplateEntryRoom;
		var exterior = _prototype.UsesAuthoredRooms ? ExteriorRoom : Parent.Location;
        Dictionary<IRoom, IRoom> cellMap = new();
        RoomOverlayPackage package = new(Gameworld, null, $"Autogenerated Dwelling Package {DateTime.UtcNow:R}");
        Gameworld.Add(package);
        IRoom baseRoom = new Room(package, exterior.OwningZone, _prototype.TemplateEntryRoom, true);
        cellMap[_prototype.TemplateEntryRoom] = baseRoom;
        List<IRoom> baseRooms = _prototype.GetTemplateRooms.ToList();
        foreach (IRoom room in baseRooms.Where(x => !ReferenceEquals(x, _prototype.TemplateEntryRoom)))
        {
            cellMap[room] = new Room(package, exterior.OwningZone, room, true);
        }

        if (_prototype.TemplateRoomIds.Count > 0)
		{
			RoomTemplateInstance.CopyExits(cellMap);
		}
		List<IExit> exitsAlreadyBuilt = new();
        foreach (IRoom room in baseRooms)
        {
			if (_prototype.TemplateRoomIds.Count > 0) break;
            foreach (IRoomExit exit in room.ExitsFor(null))
            {
				if (!cellMap.ContainsKey(exit.Destination)) continue;
                if (exitsAlreadyBuilt.Contains(exit.Exit))
                {
                    continue;
                }

                Exit newExit = new(Gameworld, cellMap[room], cellMap[exit.Destination], (Exit)exit.Exit);
                cellMap[room].GetOrCreateOverlay(package).AddExit(newExit);
                cellMap[exit.Destination].GetOrCreateOverlay(package).AddExit(newExit);
                exitsAlreadyBuilt.Add(exit.Exit);
            }
        }

        foreach (KeyValuePair<IRoom, IRoom> room in cellMap)
        {
			if (_prototype.TemplateRoomIds.Count > 0)
			{
				RoomTemplateInstance.CopyTemplate(room.Key, room.Value, $"Dwelling{Parent.Id}");
				_instanceRoomIds.Add(room.Value.Id);
			}
            Gameworld.ExitManager.UpdateRoomOverlayExits(room.Value, room.Value.CurrentOverlay);
        }
		if (_prototype.TemplateRoomIds.Count > 0)
		{
			package.ChangeStatus(RevisionStatus.Current, "Autogenerated", null);
			return baseRoom;
		}

        Exit frontExit = new(Gameworld, Parent.Location, baseRoom, 1.0,
            Gameworld.NonCardinalExitTemplates.Get(
                Gameworld.GetStaticLong("DefaultNonCardinalExitForDwellings")),
            _prototype.EntranceKeyword, _prototype.EntranceKeyword,
            _prototype.EntranceDescription, "the outside")
        {
            AcceptsDoor = true,
            DoorSize = _prototype.DoorSize,
            MaximumSizeToEnter = _prototype.DoorSize,
            MaximumSizeToEnterUpright = _prototype.DoorSize
        };
        IEditableRoomOverlay overlay = Parent.Location.GetOrCreateOverlay(Parent.Location.CurrentOverlay.Package);
        IEditableRoomOverlay otherOverlay = baseRoom.GetOrCreateOverlay(baseRoom.CurrentOverlay.Package);
        overlay.AddExit(frontExit);
        otherOverlay.AddExit(frontExit);
        Gameworld.ExitManager.UpdateRoomOverlayExits(Parent.Location, overlay);
        Gameworld.ExitManager.UpdateRoomOverlayExits(baseRoom, otherOverlay);
        if (_prototype.DoorProto != null)
        {
            IGameItem newItem = _prototype.DoorProto.CreateNew(null);
            frontExit.Door = newItem.GetItemType<IDoor>();
            Gameworld.Add(newItem);
            frontExit.Door.InstalledExit = frontExit;
            newItem.Login();
            newItem.HandleEvent(EventType.ItemFinishedLoading, newItem);
        }

        package.ChangeStatus(RevisionStatus.Current, "Autogenerated", null);
        return baseRoom;
    }

    private void Parent_OnLocationChanged(Form.Shape.ILocateable locatable, IRoomExit exit)
    {
		if (_prototype.UsesAuthoredRooms)
		{
			var created = EntranceRoom == null && ExteriorRoom != null;
			if (created) EntranceRoom = GenerateRooms();
			RebuildAccess();
			Changed = true;
			if (created) RoomTemplateInstance.InitialiseRooms(_instanceRoomIds.Select(x => Gameworld.Rooms.Get(x)).Where(x => x != null));
			return;
		}
        if (Parent.Location != null)
        {
            EntranceRoom = GenerateRooms();
            Changed = true;
            Parent.OnLocationChanged -= Parent_OnLocationChanged;
        }
    }

	private void RebuildAccess()
	{
		if (_accessExit != null)
		{
			Gameworld.ExitManager.UnregisterTransientExit(_accessExit);
			_accessExit = null;
		}
		if (ExteriorRoom == null || EntranceRoom == null) return;
		_lastExteriorRoomId = ExteriorRoom.Id;
		_accessExit = new TransientExit(Gameworld, ExteriorRoom, EntranceRoom, "enter",
			_prototype.EntranceKeyword, "outside", _prototype.EntranceDescription, "the outside", "into", "out of", 1.0,
			stableKey: $"dwelling:{Parent.Id}:entrance")
		{
			MaximumSizeToEnter = _prototype.DoorSize, MaximumSizeToEnterUpright = _prototype.DoorSize
		};
		Gameworld.ExitManager.RegisterTransientExit(_accessExit);
	}

	public override void Login()
	{
		base.Login();
		if (_prototype.UsesAuthoredRooms) RebuildAccess();
		if (_instanceRoomIds.Count > 0)
			RoomTemplateInstance.InitialiseRooms(_instanceRoomIds.Select(x => Gameworld.Rooms.Get(x)).Where(x => x != null));
	}

	public override void Quit()
	{
		ParentRemovedFromLocation(Parent);
		base.Quit();
	}

    private void DestroyRooms()
    {
		if (_prototype.UsesAuthoredRooms)
		{
			if (_accessExit != null) Gameworld.ExitManager.UnregisterTransientExit(_accessExit);
			if (_prototype.SharedInterior) return;
			var fallback = ExteriorRoom ?? Gameworld.Rooms.Get(_lastExteriorRoomId);
			if (fallback != null)
				foreach (var id in _instanceRoomIds)
					Gameworld.Rooms.Get(id)?.Destroy(fallback);
			return;
		}
        if (EntranceRoom == null)
        {
            return;
        }

        IRoom fallbackRoom = Gameworld.ExitManager.GetAllExits(EntranceRoom)
                                    .First(x => !x.Destination.Temporary &&
                                                x.OutboundDirection == CardinalDirection.Unknown).Destination;
        foreach (IRoom room in EntranceRoom.RoomsInVicinity(10U, exit => true, room => room.Temporary))
        {
            room.Destroy(fallbackRoom);
        }
    }

    #region Overrides of GameItemComponent

    /// <summary>
    ///     Handles any finalisation that this component needs to perform before being deleted.
    /// </summary>
    public override void Delete()
    {
        Parent.OnLocationChanged -= Parent_OnLocationChanged;
		Parent.OnRemovedFromLocation -= ParentRemovedFromLocation;
        base.Delete();
        DestroyRooms();
    }

    #endregion

    #region Constructors

    public DwellingGameItemComponent(DwellingGameItemComponentProto proto, IGameItem parent, bool temporary = false) :
        base(parent, proto, temporary)
    {
        _prototype = proto;
        Parent.OnLocationChanged += Parent_OnLocationChanged;
		Parent.OnRemovedFromLocation += ParentRemovedFromLocation;
        Changed = true;
    }

    public DwellingGameItemComponent(MudSharp.Models.GameItemComponent component, DwellingGameItemComponentProto proto,
        IGameItem parent) : base(component, parent)
    {
        _prototype = proto;
        _noSave = true;
        LoadFromXml(XElement.Parse(component.Definition));
        _noSave = false;
		if (_prototype.UsesAuthoredRooms) Parent.OnLocationChanged += Parent_OnLocationChanged;
		if (_prototype.UsesAuthoredRooms) Parent.OnRemovedFromLocation += ParentRemovedFromLocation;
    }

    public DwellingGameItemComponent(DwellingGameItemComponent rhs, IGameItem newParent, bool temporary = false) : base(
        rhs, newParent, temporary)
    {
        _prototype = rhs._prototype;
        if (!temporary)
        {
            Gameworld.SaveManager.AddInitialisation(this);
        }
        else
        {
            _noSave = true;
        }

        Parent.OnLocationChanged += Parent_OnLocationChanged;
		Parent.OnRemovedFromLocation += ParentRemovedFromLocation;
        Changed = true;
    }

    protected void LoadFromXml(XElement root)
    {
        _entranceRoomId = long.Parse(root.Element("EntranceCell")?.Value ?? "0");
		_instanceRoomIds.AddRange((root.Element("InstanceRooms")?.Elements("Room") ?? Enumerable.Empty<XElement>()).Select(x => (long)x));
		_lastExteriorRoomId = (long?)root.Element("LastExteriorRoom") ?? 0;
    }

    public override IGameItemComponent Copy(IGameItem newParent, bool temporary = false)
    {
        return new DwellingGameItemComponent(this, newParent, temporary);
    }

    #endregion

    #region Saving

    protected override string SaveToXml()
    {
        return new XElement("Definition",
            new XElement("EntranceCell", EntranceRoom?.Id ?? 0),
			new XElement("InstanceRooms", _instanceRoomIds.Select(x => new XElement("Room", x))),
			new XElement("LastExteriorRoom", _lastExteriorRoomId)
        ).ToString();
    }

    #endregion
}
